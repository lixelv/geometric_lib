def area(a, h):
    """
    Calculates the area of a triangle

        Params:
            a (int / float): The base of the triangle
            h (int / float): The height of the triangle tough the base

        Result:
            area (int / float): The area of the triangle
    """
    return a * h / 2


def perimeter(a, b, c):
    """
    Calculates the perimeter of a triangle

        Params:
            a (int / float): First side of the triangle
            b (int / float): Second side of the triangle
            c (int / float): Third side of the triangle

        Result:
            perimeter (int / float): The perimeter of the triangle
    """
    return a + b + c
