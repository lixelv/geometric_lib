def area(a, b):
    '''
    Calculates the area of a rectangle
    
        Params:
            a (int / float): First side of the rectangle
            b (int / float): Second side of the rectangle
        
        Result:
            area (int / float): The area of the rectangle
    '''
    return a * b 

def perimeter(a, b): 
    ''' 
    Calculates the perimeter of a rectangle
    
        Params:
            a (int / float): First side of the rectangle
            b (int / float): Second side of the rectangle
        
        Result:
            perimeter (int / float): The perimeter of the rectangle
    '''
    return (a + b) * 2
